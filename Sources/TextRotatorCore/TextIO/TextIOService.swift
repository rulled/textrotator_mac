// MARK: - Types & Protocol

public extension NSPasteboard.PasteboardType {
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
}

public enum TextIOError: Error, LocalizedError, Sendable, Equatable {
    case eventSimulationFailed
    case insertionFailed(String)
    case accessibilityUnavailable

    public var errorDescription: String? {
        switch self {
        case .eventSimulationFailed:
            return "Failed to simulate keyboard event for text operation."
        case .insertionFailed(let reason):
            return "Text insertion failed: \(reason)"
        case .accessibilityUnavailable:
            return "Accessibility permissions are not granted."
        }
    }
}

public protocol TextIOServiceProtocol: Sendable {
    /// Захват выделенного в данный момент текста в активном приложении
    func captureSelectedText() async -> String?
    
    /// Вставка текста в активное приложение с выбором оптимальной стратегии
    func insertText(_ text: String) async throws
    
    /// Проверка прав Accessibility
    func isAccessibilityGranted() -> Bool
    
    /// Запрос прав Accessibility у системы
    func promptAccessibilityPermission()
}

// MARK: - Driver Protocols (for modularity & testing)

public protocol TextAccessibilityDriver: Sendable {
    func isProcessTrusted() -> Bool
    func promptAccessibility()
