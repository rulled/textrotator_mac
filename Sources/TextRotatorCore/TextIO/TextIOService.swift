public protocol AppActivationDriver: Sendable {
    func activateFrontmostAppIfNeeded()
}

// MARK: - System Driver Implementations

public final class SystemAccessibilityDriver: TextAccessibilityDriver, @unchecked Sendable {
    public init() {}

    public func isProcessTrusted() -> Bool {
        AXIsProcessTrusted()
    }

    public func promptAccessibility() {
        let promptKey = "AXTrustedCheckOptionPrompt" as CFString
        let options = [promptKey: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    private func getFocusedUIElement() -> AXUIElement? {
        let systemWide = AXUIElementCreateSystemWide()
        var focusedAppRef: AnyObject?
        guard AXUIElementCopyAttributeValue(
            systemWide,
            kAXFocusedApplicationAttribute as CFString,
            &focusedAppRef
        ) == .success,
              let focusedApp = focusedAppRef,
              CFGetTypeID(focusedApp) == AXUIElementGetTypeID() else {
            return nil
        }

        let appElement = focusedApp as! AXUIElement
        var focusedElementRef: AnyObject?
        guard AXUIElementCopyAttributeValue(
            appElement,
            kAXFocusedUIElementAttribute as CFString,
            &focusedElementRef
        ) == .success,
              let focusedElement = focusedElementRef,
              CFGetTypeID(focusedElement) == AXUIElementGetTypeID() else {
            return nil
        }

        return (focusedElement as! AXUIElement)
    }

    public func copySelectedText() -> String? {
        guard let uiElement = getFocusedUIElement() else {
            return nil
        }

        var selectedTextRef: AnyObject?
        guard AXUIElementCopyAttributeValue(
            uiElement,
            kAXSelectedTextAttribute as CFString,
            &selectedTextRef
        ) == .success,
              let selectedText = selectedTextRef as? String,
              !selectedText.isEmpty else {
            return nil
        }

        return selectedText
    }

    public func setSelectedText(_ text: String) -> Bool {
        guard let uiElement = getFocusedUIElement() else {
            return false
        }

        let status = AXUIElementSetAttributeValue(
            uiElement,
            kAXSelectedTextAttribute as CFString,
            text as CFTypeRef
        )
        return status == .success
    }
}

public final class SystemPasteboardDriver: TextPasteboardDriver, @unchecked Sendable {
    private let pasteboard: NSPasteboard

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public func clearContents() -> Int {
        pasteboard.clearContents()
    }

    public func setString(_ string: String, forType type: NSPasteboard.PasteboardType) -> Bool {
        pasteboard.setString(string, forType: type)
    }

    public func string(forType type: NSPasteboard.PasteboardType) -> String? {
        pasteboard.string(forType: type)
    }

    public func changeCount() -> Int {
        pasteboard.changeCount
    }
}

public final class SystemKeyEventSimulatorDriver: KeyEventSimulatorDriver, @unchecked Sendable {
    public init() {}

    public func simulateKey(keyCode: CGKeyCode, flags: CGEventFlags) -> Bool {
        guard let keyDown = CGEvent(keyboardEventSource: nil, virtualKey: keyCode, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: nil, virtualKey: keyCode, keyDown: false) else {
            return false
        }
        keyDown.flags = flags
        keyUp.flags = flags
        keyDown.post(tap: .cghidEventTap)
        keyUp.post(tap: .cghidEventTap)
        return true
    }
}

public final class SystemAppActivationDriver: AppActivationDriver, @unchecked Sendable {
    public init() {}

    public func activateFrontmostAppIfNeeded() {
        if let frontApp = NSWorkspace.shared.frontmostApplication, !frontApp.isActive {
            frontApp.activate()
        }
    }
}

// MARK: - TextIOService

public final class TextIOService: TextIOServiceProtocol, @unchecked Sendable {
    public static let shared = TextIOService()

    private let accessibilityDriver: TextAccessibilityDriver
    private let pasteboardDriver: TextPasteboardDriver
    private let keyEventSimulator: KeyEventSimulatorDriver
    private let appActivationDriver: AppActivationDriver

    public init(
        accessibilityDriver: TextAccessibilityDriver = SystemAccessibilityDriver(),
        pasteboardDriver: TextPasteboardDriver = SystemPasteboardDriver(),
        keyEventSimulator: KeyEventSimulatorDriver = SystemKeyEventSimulatorDriver(),
        appActivationDriver: AppActivationDriver = SystemAppActivationDriver()
    ) {
        self.accessibilityDriver = accessibilityDriver
        self.pasteboardDriver = pasteboardDriver
        self.keyEventSimulator = keyEventSimulator
        self.appActivationDriver = appActivationDriver
    }

    /// Проверка прав Accessibility
    public func isAccessibilityGranted() -> Bool {
        accessibilityDriver.isProcessTrusted()
    }

    /// Запрос прав Accessibility у системы
    public func promptAccessibilityPermission() {
        accessibilityDriver.promptAccessibility()
    }

    /// Захват выделенного в данный момент текста в активном приложении
    /// - Method 1: AX direct reading (kAXFocusedApplicationAttribute -> kAXFocusedUIElementAttribute -> kAXSelectedTextAttribute)
    /// - Method 2 (fallback): Cmd+C pasteboard simulation with changeCount poll up to 100ms
    public func captureSelectedText() async -> String? {
        // Method 1: AXUIElement direct query
        if let directText = accessibilityDriver.copySelectedText(), !directText.isEmpty {
            return directText
        }

        // Method 2: Fallback via Cmd+C simulation and pasteboard changeCount tracking
        let initialChangeCount = pasteboardDriver.changeCount()

        // 0x08 is virtual key code for 'c' (kVK_ANSI_C)
        let keySimulated = keyEventSimulator.simulateKey(keyCode: 0x08, flags: .maskCommand)
        guard keySimulated else {
            return nil
        }

        // Wait up to 100ms for pasteboard update (10 iterations of 10ms)
        let intervalNanos: UInt64 = 10_000_000 // 10ms
        let maxChecks = 10

        for _ in 0..<maxChecks {
            try? await Task.sleep(nanoseconds: intervalNanos)
            if pasteboardDriver.changeCount() != initialChangeCount {
                if let copiedText = pasteboardDriver.string(forType: .string), !copiedText.isEmpty {
                    return copiedText
                }
                return nil
            }
        }

        return nil
    }

    /// Вставка текста в активное приложение с выбором оптимальной стратегии
    /// - Level 1: Attempt direct in-place replacement via AXUIElementSetAttributeValue
    /// - Level 2 (fallback): Write to pasteboard with concealment types and simulate Cmd+V (0x09)
    public func insertText(_ text: String) async throws {
        // Level 1: AX direct in-place replacement
        if accessibilityDriver.setSelectedText(text) {
            return
        }

        // Level 2 (fallback): Concealed pasteboard write + Cmd+V simulation
        appActivationDriver.activateFrontmostAppIfNeeded()

        _ = pasteboardDriver.clearContents()
        _ = pasteboardDriver.setString(text, forType: .string)

        // Add concealment metadata to prevent history logging by clipboard managers (Raycast, Maccy, Paste, Alfred)
        _ = pasteboardDriver.setString("", forType: .transient)
        _ = pasteboardDriver.setString("", forType: .autoGenerated)
        _ = pasteboardDriver.setString("", forType: .concealed)

        // 0x09 is virtual key code for 'v' (kVK_ANSI_V)
        let keySimulated = keyEventSimulator.simulateKey(keyCode: 0x09, flags: .maskCommand)
        guard keySimulated else {
            throw TextIOError.eventSimulationFailed
        }
    }
}
